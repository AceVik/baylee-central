//! Permanent v2 Tower accomplishments. No shops, economy, rules or matchmaking.
use crate::Error;
use serde::{Deserialize, Serialize};

mod progress;
pub use progress::{Badge, BadgeKind, Progress};

/// Independently verified terminal duel outcome; a technical fault has no variant.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Outcome {
    /// One victory toward an eight-win expedition.
    Victory,
    /// One spent life toward the five-defeat limit.
    Defeat,
    /// A rules draw spends one life too; an outage is never a rules draw.
    Draw,
}

/// Strict, immutable fact from the separate approved Tower verifier authority.
/// Validation is not issuer authentication or proof that a game was replayed.
#[derive(Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Fact {
    /// Accomplishment schema, exactly two for the eight-win/five-life expedition.
    pub schema: u16,
    /// Stable run `UUIDv7` generated by the Tower database.
    pub run: [u8; 16],
    /// Immutable compatibility cohort `UUIDv7`.
    pub cohort: [u8; 16],
    /// Completed one-based duel ordinal, at most twelve.
    pub stage: u8,
    /// Verified terminal result.
    pub outcome: Outcome,
    /// Cumulative victories after this duel.
    pub wins: u8,
    /// Cumulative defeats and rules draws after this duel.
    pub defeats: u8,
}

impl Fact {
    /// Validate the permanent-accomplishment contract, without running game rules.
    /// # Errors
    /// Unsupported schema, malformed identifiers or impossible completed counts.
    pub fn validate(&self) -> Result<(), Error> {
        let victory = self.outcome == Outcome::Victory;
        if self.schema != 2
            || !uuid7(self.run)
            || !uuid7(self.cohort)
            || !(1..=12).contains(&self.stage)
            || self.wins > 8
            || self.defeats > 5
            || self.wins.checked_add(self.defeats) != Some(self.stage)
            || (victory && (self.wins == 0 || self.defeats == 5))
            || (!victory && (self.defeats == 0 || self.wins == 8))
        {
            return Err(Error::Rejected);
        }
        Ok(())
    }

    /// Check the next fact against the run's last receipt, or its first ordinal.
    /// Out-of-order delivery retries later; it never projects an incomplete run.
    /// # Errors
    /// Invalid facts, missing ordinals, changed run/cohort or an already ended run.
    pub fn follows(&self, earlier: Option<&Self>) -> Result<(), Error> {
        self.validate()?;
        let Some(earlier) = earlier else {
            return if self.stage == 1 {
                Ok(())
            } else {
                Err(Error::Conflict)
            };
        };
        earlier.validate()?;
        let gap = self
            .stage
            .checked_sub(earlier.stage)
            .ok_or(Error::Conflict)?;
        let wins = self.wins.checked_sub(earlier.wins).ok_or(Error::Conflict)?;
        let defeats = self
            .defeats
            .checked_sub(earlier.defeats)
            .ok_or(Error::Conflict)?;
        if self.run != earlier.run
            || self.cohort != earlier.cohort
            || gap != 1
            || wins.checked_add(defeats) != Some(gap)
            || earlier.wins == 8
            || earlier.defeats == 5
            || (self.outcome == Outcome::Victory && wins == 0)
            || (self.outcome != Outcome::Victory && defeats == 0)
        {
            return Err(Error::Conflict);
        }
        Ok(())
    }
}

/// Exact event/account envelope from the authenticated issuer, never a player score.
#[derive(Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Delivery {
    /// Stable outbox `UUIDv7`; retries preserve it exactly.
    pub event: [u8; 16],
    /// Existing Central account `UUIDv7`, rechecked at ingestion.
    pub account: [u8; 16],
    /// Minimal immutable verified progression.
    pub fact: Fact,
}

impl Delivery {
    /// Check shape; authentication, account lifecycle and receipts belong to storage.
    /// # Errors
    /// Malformed identifiers or invalid fact.
    pub fn validate(&self) -> Result<(), Error> {
        if !uuid7(self.event) || !uuid7(self.account) {
            return Err(Error::Rejected);
        }
        self.fact.validate()
    }
}

const fn uuid7(id: [u8; 16]) -> bool {
    id[6] >> 4 == 7 && id[8] >> 6 == 2
}

