//! Closed version-one request/response vocabulary. No secret-bearing type implements Debug.
use crate::Token;
use crate::terms::{TermsDocument, TermsSubject, TermsText, TermsVersion};
use serde::{Deserialize, Serialize};

/// A gateway capability authorizes exactly one action, never a general account session.
#[derive(Clone, Copy, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TicketPurpose {
    /// Admit to gameplay using an already-linked account.
    Admit,
    /// Read a source snapshot to resume interrupted migration.
    Export,
    /// Finalize the immutable account link after successful restore.
    Link,
    /// Authenticate a gateway administrator; current gateway membership is mandatory.
    Admin,
}

impl TicketPurpose {
    /// Stable database representation.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Admit => "admit",
            Self::Export => "export",
            Self::Link => "link",
            Self::Admin => "admin",
        }
    }
}

/// Immutable identity metadata authenticated by the configured central HTTPS endpoint.
#[derive(Clone, Copy, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Identity {
    /// Database-generated `UUIDv7`.
    pub account: [u8; 16],
    /// Vault epoch; authentication resets never silently initialize another vault.
    pub epoch: u64,
}

/// Native client request, serialized as a tagged object. Bearer credentials belong in headers.
#[derive(Serialize, Deserialize)]
#[serde(tag = "operation", rename_all = "snake_case", deny_unknown_fields)]
pub enum Request {
    /// Contacts and encrypted chat shared by native and browser sessions.
    /// Browser notification preferences and subscriptions.
    Notifications {
        /// Closed notification operation.
        request: crate::notifications::NotificationRequest,
    },
    /// Account contacts and encrypted conversations.
    Social {
        /// A closed social operation; account ownership comes only from the session.
        request: crate::social::SocialRequest,
    },
    /// Check a live session without downloading personal ciphertext or extending its lifetime.
    SessionStatus,
    /// Renew a live session: it expires 30 minutes from now, never later than
    /// 12 hours after the password sign-in that issued it, and its gateway
    /// leases follow. Answered with [`Response::Renewed`].
    RenewSession,
    /// Reserve an opaque object ID generated by PostgreSQL.
    CreateObject,
    /// Read one account-owned encrypted object.
    ReadObject {
        /// Opaque `UUIDv7` from this account's encrypted manifest.
        id: [u8; 16],
    },
    /// Paginated owned object identities for interrupted-upload reconciliation.
    ListObjects {
        /// Last ID from the preceding page; at most 100 results are returned.
        after: Option<[u8; 16]>,
    },
    /// Compare-and-swap encrypted object content.
    WriteObject {
        /// Account-owned object ID.
        id: [u8; 16],
        /// Previously authenticated revision, or zero for an unwritten reservation.
        expected_revision: u64,
        /// Client ciphertext authenticated under the next revision and object identity.
        document: Vec<u8>,
    },
    /// Tombstone an owned object without permitting recreation under the same identity.
    DeleteObject {
        /// Account-owned object ID.
        id: [u8; 16],
        /// Current object revision.
        expected_revision: u64,
    },
    /// Official bridge invalidates unfinished enrollment before a legacy password change.
    LegacyInvalidate {
        /// Original gateway account identifier; finalized accounts cannot be invalidated.
        legacy_id: String,
    },
    /// Permanently retire the bridge's enrollment reset authority after source validation.
    LegacyClose {
        /// Original gateway account identifier.
        legacy_id: String,
        /// Exact account/epoch whose decrypted source copy was restored.
        identity: Identity,
    },
    /// Request operator review of a gateway origin; registration does not approve it.
    RegisterGateway {
        /// Canonical HTTPS origin, or explicit numeric loopback in development.
        origin: String,
        /// Bounded public metadata.
        metadata: crate::gateway::GatewayMetadata,
    },
    /// Read at most 100 approved entries, ordered by immutable gateway ID.
    GatewayDirectory {
        /// Exclusive pagination cursor, or None for the first page.
        after: Option<[u8; 16]>,
    },
    /// Update only public metadata/presence using the separate heartbeat credential.
    GatewayHeartbeat {
        /// Metadata must stay on the approved origin.
        metadata: crate::gateway::GatewayMetadata,
    },
    /// A heartbeat that also reports activity: the same credential, checks,
    /// limit and answer as [`Request::GatewayHeartbeat`], and the four
    /// counts kept with the time. A plain heartbeat afterwards clears them:
    /// the gateway stopped reporting. Sending this is the operator's choice
    /// (`docs/gateway-registry.md` §"Activity and the public figures").
    GatewayPulse {
        /// Metadata must stay on the approved origin.
        metadata: crate::gateway::GatewayMetadata,
        /// The gateway's own counts, each at most
        /// [`crate::gateway::GatewayActivity::MOST`], and no more players in
        /// a game than connected.
        activity: crate::gateway::GatewayActivity,
    },
    /// Public, no credential: the number of accounts, and one page of what
    /// online gateways last reported. Answered with
    /// [`Response::PublicFigures`]; served like [`Request::GatewayDirectory`],
    /// under its budgets.
    PublicFigures {
        /// Exclusive pagination cursor, or None for the first page.
        after: Option<[u8; 16]>,
    },
    /// Owner-authorized, revision-checked replacement of this gateway's administrator list.
    SetGatewayAdmins {
        /// Owned gateway ID.
        gateway: [u8; 16],
        /// Expected administrator-list revision, initially 1.
        expected_revision: u64,
        /// At most 32 distinct central account IDs; the owner remains an administrator.
        accounts: Vec<[u8; 16]>,
    },
    /// Gateway-authenticated check of current administrator membership.
    CheckGatewayAdmin {
        /// Immutable central account ID.
        account: [u8; 16],
    },
    /// Revalidate an opaque gateway-held lease against the live central session.
    GatewaySession {
        /// Lease returned only to the redeeming gateway, never its client.
        lease: Token,
        /// Exactly Admit or Admin; purposes cannot be promoted.
        purpose: TicketPurpose,
    },
    /// Resolve a private login name. Unknown names receive the same legacy eligibility result.
    Discover {
        /// Username as entered, canonicalized by the service's versioned name policy.
        username: String,
    },
    /// First OPAQUE login message.
    LoginStart {
        /// Account mapping from discovery, checked again by the server.
        identity: Identity,
        /// KE1; exact suite length is enforced before expensive processing.
        message: Vec<u8>,
    },
    /// Final OPAQUE proof. A pending attempt is consumed on success and failure.
    LoginFinish {
        /// Random short-lived attempt capability.
        attempt: Token,
        /// KE3, not a password.
        message: Vec<u8>,
    },
    /// Authenticated legacy gateway reserves an identity after fresh password verification.
    LegacyReserve {
        /// Immutable ID at the sole configured legacy gateway; never an email match.
        legacy_id: String,
        /// Canonical username vouched for by the authenticated migration bridge.
        username: String,
        /// The legacy account's display name, kept as it is when it keeps
        /// [`crate::profile::valid_display_name`]; the bridge sends none for
        /// a name that does not, and the account chooses one on the website.
        /// Absent on the wire when `None`, so bridges built before it still
        /// decode and are still decoded.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        display_name: Option<String>,
        /// The legacy account's tag, kept unless another account holds it
        /// already, when it draws a new one. Absent on the wire when `None`.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        tag: Option<u32>,
    },
    /// A legacy account's sign-in from Central's legacy store
    /// (`docs/native-login.md` §"Legacy login"), on the native listener only
    /// and only before the store's deadline: the username and the old
    /// password, which Central verifies against the gateway's hash and
    /// forgets. With the password proven and no forced change or ban in
    /// force, Central reserves the account's identity under its name and tag
    /// and answers [`Response::LegacyEnrollment`]; `Conflict` once it is
    /// enrolled. Every refusal before the proof (an unknown, closed, locked
    /// or registered name, a wrong password) is the same `Rejected`.
    LegacyLogin {
        /// Username as entered, canonicalized by the service's name policy.
        username: String,
        /// The old password; sent once, never stored or logged.
        password: crate::legacy::LegacyPassword,
    },
    /// The session's account's source snapshot again, while its move is
    /// open, with Central's terms accepted: for a client whose restored
    /// document names another digest. Answered with
    /// [`Response::LegacySnapshot`].
    LegacyExport,
    /// Close the session's account's move once its document is restored,
    /// with Central's terms accepted: `digest` must be the stored
    /// snapshot's. The account's row leaves the legacy store; the official
    /// gateway learns the link at the account's next admission there. Again
    /// after the close is `Done`; a wrong digest is `Conflict`.
    LegacyLink {
        /// The source digest the restored document holds.
        digest: [u8; 32],
    },
    /// Carry a legacy account's display name and tag once, for an account
    /// reserved before Central kept them (bridge only): `Done` when they were
    /// set, `Conflict` when the account has its tag already (and with it any
    /// name), so a bridge may send it at every sign-in.
    LegacyProfile {
        /// Original gateway account identifier.
        legacy_id: String,
        /// Its display name, or none when it does not keep the rule.
        display_name: Option<String>,
        /// Its tag at the official gateway.
        tag: u32,
    },
    /// The request for the older, SHA-256 proof of work
    /// ([`Response::RegisterChallenge`]), on the browser listener only. A
    /// Central of this build issues no such challenge: it answers
    /// [`Response::RegistrationClosed`] whether registration is open or
    /// not, and the registering side asks with
    /// [`Request::RegisterChallengeFor`]
    /// (`docs/registration-abuse.md` §"A proof that costs memory").
    RegisterChallenge,
    /// A proof-of-work challenge for one registration, on the browser
    /// listener only, asked by a page that says what it saw of its own
    /// browser (`docs/registration-abuse.md` §"Hardened"): the answer is
    /// [`Response::RegisterWork`], or [`Response::RegistrationClosed`]
    /// while an administrator closed registration, and a browser that
    /// looks driven by a program gets a harder challenge, never a refusal.
    RegisterChallengeFor {
        /// [`crate::register::SIGNALS`]; bits Central does not know are
        /// ignored.
        signals: u8,
    },
    /// Reserve a new registered account, on the browser listener only
    /// (`docs/web-accounts.md`), while registration is open (`Rejected`
    /// while an administrator closed it). The challenge's solution is
    /// checked and spent first: a bad one is `Rejected` before the name is
    /// looked at; only then is a taken name `Conflict`.
    Register {
        /// Wanted username, canonicalized by the service's versioned name policy.
        username: String,
        /// The challenge's nonce ([`Response::RegisterWork`]).
        nonce: String,
        /// One counter per part ([`crate::register`]). The price they are
        /// checked against is the one Central kept with the nonce.
        counters: Vec<u64>,
        /// The display name other players see, chosen now; a malformed or
        /// reserved one is `Rejected`, after the proof is spent. `None` chooses it
        /// later on the account page. The tag is drawn with the reservation.
        /// Absent on the wire when `None`.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        display_name: Option<String>,
    },
    /// An enrollment capability authorizes a response, not replacement of an existing record.
    EnrollmentStart {
        /// Short-lived capability returned through the authenticated legacy login.
        ticket: Token,
        /// OPAQUE registration request.
        message: Vec<u8>,
    },
    /// Atomic first enrollment: credential, key wrapper and initial encrypted manifest.
    EnrollmentFinish {
        /// Same operation capability; consumed only by the atomic successful commit.
        ticket: Token,
        /// OPAQUE registration upload.
        record: Vec<u8>,
        /// Client-encrypted random master key, exactly 73 bytes.
        wrapped_master: Vec<u8>,
        /// Initial encrypted account document. Central never receives its plaintext.
        document: Vec<u8>,
        /// The same master key wrapped under the recovery code, exactly 73 bytes:
        /// required for a registered account, refused for a legacy one. Absent on
        /// the wire when `None`, so clients built before it still decode and are
        /// still decoded.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        recovery: Option<Vec<u8>>,
    },
    /// Restore the account document after final OPAQUE authentication.
    ReadDocument,
    /// Compare-and-swap an encrypted account document, never unconditional overwrite.
    WriteDocument {
        /// Last authenticated revision read by this client.
        expected_revision: u64,
        /// Ciphertext authenticated under `expected_revision` + 1.
        document: Vec<u8>,
    },
    /// Client has restored and authenticated its first central copy.
    ConfirmRestore {
        /// Revision whose ciphertext the client successfully authenticated and restored.
        revision: u64,
    },
    /// Migration bridge queries durable cutover state; no client assertion is accepted.
    LegacyStatus {
        /// Original gateway account identifier.
        legacy_id: String,
    },
    /// Issue a one-use ticket scoped to a configured gateway; never forward a central session.
    GatewayTicket {
        /// Exact canonical gateway origin.
        gateway: String,
        /// Single action authorized by this ticket.
        purpose: TicketPurpose,
    },
    /// Configured gateway redeems its own audience-bound ticket.
    RedeemGateway {
        /// One-use, short-lived ticket delivered by the native client.
        ticket: Token,
        /// Action enforced by the receiving gateway route.
        purpose: TicketPurpose,
    },
    /// Revoke the presented central session immediately.
    Logout,
    /// Central's terms in force, or none. Needs no credential.
    Terms,
    /// A gateway's current terms, or none. Needs no credential.
    GatewayTerms {
        /// The gateway's canonical origin.
        origin: String,
    },
    /// Central's current terms version and whether this session's account accepted it.
    TermsStatus,
    /// Record that this session's account accepted exactly this version; only
    /// the subject's current version and digest are accepted.
    AcceptTerms {
        /// Central or a gateway origin.
        subject: TermsSubject,
        /// The version shown.
        version: String,
        /// Digest of the texts shown.
        digest: [u8; 32],
    },
    /// The authenticated gateway publishes a version of its own terms; a
    /// published version never changes.
    PublishGatewayTerms {
        /// New version; never `draft`.
        version: String,
        /// Its languages in ascending tag order.
        texts: Vec<TermsText>,
    },
    /// [`Request::GatewaySession`] plus the account's terms state.
    GatewayAuthorize {
        /// Lease returned only to the redeeming gateway, never its client.
        lease: Token,
        /// Exactly Admit or Admin; purposes cannot be promoted.
        purpose: TicketPurpose,
        /// The gateway's own current terms, or none when it has none.
        terms: Option<TermsVersion>,
    },
    /// The browser session's account, for the account page: who, where it
    /// came from, whether it has a recovery code, and when the session's
    /// password sign-in was. Browser listener only; needs no accepted terms.
    /// Answered with [`Response::AccountSummary`].
    AccountSummary,
    /// Store the master key wrapped under a recovery code made after a
    /// sign-in, for an account that has none (one moved from the official
    /// gateway): browser listener only, with accepted terms, within 10
    /// minutes of the browser session's password sign-in. The same bytes
    /// again are `Done` at any time; other bytes while a wrapper exists are
    /// `Conflict` (`docs/web-accounts.md`).
    SetRecovery {
        /// The master key under the recovery code, exactly 73 bytes.
        recovery: Vec<u8>,
    },
    /// Choose the display name of the browser session's account, which has
    /// none yet (renaming comes later): browser listener only, with accepted
    /// terms. The same name again is `Done`; another while one is set is
    /// `Conflict`; a malformed or reserved name, or an account moved from the
    /// official gateway whose name and tag the bridge has not carried yet, is
    /// `Rejected` (`docs/web-accounts.md`).
    SetDisplayName {
        /// The name, kept as typed: [`crate::profile::choosable`].
        display_name: String,
    },
    /// The display name and tag of the account behind a live lease the
    /// asking gateway holds, under its redemption credential or the bridge,
    /// as [`Request::GatewaySession`]: a gateway learns the names of the
    /// people who sign in there, nobody else's. Answered with
    /// [`Response::GatewayProfile`].
    GatewayProfile {
        /// Lease returned only to the redeeming gateway, never its client.
        lease: Token,
        /// Exactly Admit or Admin; purposes cannot be promoted.
        purpose: TicketPurpose,
    },
    /// Begin changing the password of the session's account, on either
    /// listener, with Central's terms accepted: a fresh OPAQUE login with the
    /// current password and an OPAQUE registration of the new one, for the
    /// session's own account and epoch. The account must have finished
    /// moving. Answered with [`Response::PasswordChallenge`]; it shares the
    /// per-account login budget (`docs/native-login.md` §"Password change").
    ChangePasswordStart {
        /// KE1 under the current password.
        login: Vec<u8>,
        /// OPAQUE registration request for the new password.
        registration: Vec<u8>,
    },
    /// Finish a password change with the session that started it: the proof
    /// of the current password, the new record and the same master key
    /// wrapped under the new password. Every session of the account ends and
    /// one new session of the calling listener's kind is answered, as
    /// `LoginFinish` answers it; the vault epoch, documents, objects and
    /// recovery wrapper stay as they are.
    ChangePasswordFinish {
        /// The attempt of [`Response::PasswordChallenge`], consumed on
        /// success and failure.
        attempt: Token,
        /// KE3 under the current password, not a password.
        proof: Vec<u8>,
        /// OPAQUE registration upload for the new password.
        record: Vec<u8>,
        /// The account's master key wrapped under the new password, exactly
        /// 73 bytes.
        wrapped_master: Vec<u8>,
    },
    /// Begin setting a new password with a reset code an administrator made
    /// (`docs/account-reset.md`), on either listener without a session: an
    /// OPAQUE registration request for the new password. A valid, unexpired
    /// code for this username spends one unit of the account's login budget
    /// and is answered with [`Response::ResetChallenge`]; anything else is
    /// `Rejected`, spending nothing of the account's.
    ResetStart {
        /// The account's username, as typed.
        username: String,
        /// The code, as typed; it must carry its `RESET` prefix.
        code: crate::reset_code::ResetCode,
        /// OPAQUE registration request for the new password.
        registration: Vec<u8>,
    },
    /// Finish a reset: the new record and the master key wrapped under the new
    /// password, keeping the vault or making a new one. Spends the code, ends
    /// every session; `Done`. A lost answer cannot be retried: sign in with the
    /// new password to learn whether it took.
    ResetFinish {
        /// The attempt of [`Response::ResetChallenge`], consumed on success and
        /// failure.
        attempt: Token,
        /// OPAQUE registration upload for the new password.
        record: Vec<u8>,
        /// The (kept or new) master key under the new password, 73 bytes.
        wrapped_master: Vec<u8>,
        /// What happens to the encrypted data.
        vault: ResetVault,
    },
    /// The session's account and its optional e-mail address
    /// (`docs/email.md`), on either listener. Naming, mailing and
    /// confirming an address need Central's terms accepted; reading,
    /// withdrawing and removing do not. Naming one also needs a password
    /// sign-in less than five minutes old. Answered with
    /// [`Response::Email`].
    Email {
        /// The action.
        request: crate::email::EmailRequest,
    },
    /// Ask for a reset code by mail, without a session (`docs/email.md`
    /// §"A reset code by mail"). Central answers `Done` whatever the name:
    /// a code goes to the account's confirmed address if the name is an
    /// account that has one and may be reset; nobody else learns which.
    /// `Busy` when the asking address or Central as a whole asked too
    /// often, `Rejected` for every name where Central sends no mail. The
    /// code is redeemed as an administrator's is ([`Request::ResetStart`]).
    ResetMail {
        /// The account's sign-in name, as [`Request::Discover`] takes it.
        username: String,
        /// The language of the mail ([`crate::email::language`]).
        lang: String,
    },
    /// An account's request about its own sessions and gateways
    /// (`docs/web-accounts.md` §"The account area"): browser listener only,
    /// the cookie's session, Central's terms accepted; minting a token also
    /// needs a password sign-in less than 30 minutes old. Answered with
    /// [`Response::Owner`], or `Done` for a change that creates nothing.
    Owner {
        /// The action.
        request: crate::owner::OwnerRequest,
    },
    /// What Central knows about the gateway whose token authenticates this
    /// request (`docs/gateway-registry.md` §"Gateway tokens"): its origin,
    /// metadata and approval, and the token's scopes and expiry. Answered
    /// for a live token whatever the approval, so a new gateway's console
    /// can say it waits for one; anything else is `Rejected`.
    GatewayStatus,
    /// An administrator's request (`docs/administration.md`): browser
    /// listener only, a browser session whose account holds the role, and
    /// Central's terms accepted; a change also needs a password sign-in less
    /// than 30 minutes old. Answered with [`Response::Admin`], or `Done` for
    /// a change.
    Admin {
        /// The action.
        request: crate::admin::AdminRequest,
    },
    /// Everything Central stores about the session's account apart from its
    /// secrets and ciphertext (`docs/account-deletion.md`), on either
    /// listener. Needs a password sign-in less than 30 minutes old, not
    /// Central's terms. Answered with [`Response::AccountExport`].
    AccountExport,
    /// Begin deleting the session's account, on either listener, without
    /// Central's terms: a fresh OPAQUE login with the password, for the
    /// session's own account and epoch. The account must have finished
    /// moving and hold no administrator role. Answered with
    /// [`Response::DeleteChallenge`]; it spends one unit of the account's
    /// login budget.
    DeleteAccountStart {
        /// KE1 under the password.
        login: Vec<u8>,
    },
    /// Finish a deletion with the session that started it: the account, the
    /// gateways it owns and every row naming it are deleted; `Done`, and on
    /// the browser listener the cookie is cleared. Cannot be undone.
    DeleteAccountFinish {
        /// The attempt of [`Response::DeleteChallenge`], consumed on success
        /// and failure.
        attempt: Token,
        /// KE3 under the password, not a password.
        proof: Vec<u8>,
    },
    /// Whether the session's account has a key check (`docs/web-accounts.md`
    /// §"Pairing"), on either listener. Answered with [`Response::KeyCheck`].
    KeyCheckStatus,
    /// Store the account's key check, on either listener: accepted once,
    /// while none is set and within two minutes of the session's password
    /// proof. `Done`; `Conflict` when one is set, `Rejected` when too late.
    SetKeyCheck {
        /// The 32-byte check derived from the master key.
        check: Vec<u8>,
    },
    /// Start a pairing for the browser session's account (browser listener
    /// only). Answered with [`Response::PairStarted`].
    PairStart,
    /// The pairing's claim, if a client made one (browser listener only, the
    /// session that started it). Answered with [`Response::PairClaimed`] or
    /// [`Response::Pending`].
    PairStatus {
        /// The pairing's handle.
        handle: Token,
    },
    /// Approve a claimed pairing with the sealed master key and the proof
    /// under the key check (browser listener only, the session that started
    /// it). `Done`.
    PairApprove {
        /// The pairing's handle.
        handle: Token,
        /// The master key sealed to the client's key, 80 bytes.
        sealed: Vec<u8>,
        /// HMAC-SHA-256 under the key check over the approval, 32 bytes.
        proof: Vec<u8>,
    },
    /// End a pairing at once (browser listener only). `Done`.
    PairCancel {
        /// The pairing's handle.
        handle: Token,
    },
    /// A client claims a pairing (native listener, no session): once per
    /// handle, within its first two minutes. Answered with
    /// [`Response::PairAccepted`], again for the same claim resent; another
    /// claim is `Conflict`.
    PairClaim {
        /// The pairing's handle, from the link.
        handle: Token,
        /// The client's X25519 public key, 32 bytes.
        public_key: Vec<u8>,
        /// SHA-256 of the client's verifier, 32 bytes.
        challenge: Vec<u8>,
        /// HMAC-SHA-256 under the link's secret over the claim, 32 bytes.
        mac: Vec<u8>,
    },
    /// Whether the claimed pairing was approved (native listener, no
    /// session). Answered with [`Response::Pending`] or [`Response::Approved`].
    PairPoll {
        /// The pairing's handle.
        handle: Token,
    },
    /// Redeem an approved pairing with the verifier, once (native listener,
    /// no session). Answered with [`Response::PairSession`]; the pairing is
    /// gone afterwards, also after a refusal.
    PairRedeem {
        /// The pairing's handle.
        handle: Token,
        /// The verifier whose SHA-256 the claim sent, 32 bytes.
        verifier: Vec<u8>,
    },
    /// The session's own profile picture (`docs/profile-pictures.md`), on
    /// the browser listener; Central's terms need not be accepted. The
    /// picture itself is uploaded on its own route, `PUT /api/v1/picture`.
    Picture {
        /// The action.
        request: crate::picture::PictureRequest,
    },
}

/// What a reset does with the account's encrypted data.
#[derive(Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum ResetVault {
    /// The same master key, opened with the recovery code or held by a device
    /// still signed in: the epoch, documents, objects and recovery wrapper stay.
    Keep,
    /// A new master key at the next epoch (the identity's epoch plus one):
    /// the old documents and objects, which no one can open any more, are
    /// replaced and deleted.
    New {
        /// The new first account document, sealed under the new key as object
        /// one at the new epoch.
        document: Vec<u8>,
        /// The new key under a new recovery code, 73 bytes: required for a
        /// registered account, optional for a moved one.
        recovery: Option<Vec<u8>>,
    },
}

/// Where an account came from.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AccountSource {
    /// Moved from the official gateway, which kept no recovery code.
    Legacy,
    /// Registered on the website (with a beta key while the beta was closed).
    Registered,
}

/// Account credential destination decision; transport errors are never legacy eligibility.
#[derive(Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case", deny_unknown_fields)]
pub enum Discovery {
    /// Existing enrolled account.
    Central {
        /// Authenticated account mapping.
        identity: Identity,
    },
    /// Explicit legacy enrollment path, only valid with the compiled live endpoint policy.
    Legacy,
}

/// Durable migration state visible only to its authenticated gateway bridge.
#[derive(Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum MigrationState {
    /// Enrollment has not committed; old data and login remain available.
    Pending,
    /// Credential and encrypted data committed, but restoration is not confirmed.
    Enrolled,
    /// An authenticated client confirmed successful decryption; cutover may proceed.
    Restored,
}

